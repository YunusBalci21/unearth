export function ageInYears(year, now = new Date().getFullYear()) {
    return Math.max(0, now - year);
}

/** Human readable approximate age: "c. 3,300 years old", "c. 2.6 million years old". */
export function formatAge(year, now = new Date().getFullYear()) {
    const age = ageInYears(year, now);
    if (age >= 1_000_000) return `c. ${(age / 1_000_000).toFixed(1).replace(/\.0$/, '')} million years old`;
    if (age >= 10_000) return `c. ${Math.round(age / 1000).toLocaleString('en-US')},000 years old`;
    if (age >= 1000) return `c. ${(Math.round(age / 50) * 50).toLocaleString('en-US')} years old`;
    if (age >= 100) return `c. ${Math.round(age / 10) * 10} years old`;
    return `c. ${age} years old`;
}

/** Calendar date label: "c. 1323 BC", "c. AD 120", "c. 1750". */
export function formatYear(year) {
    if (year <= -10000) return `c. ${Math.round(-year / 1000).toLocaleString('en-US')},000 BC`;
    if (year < 0) return `c. ${-year} BC`;
    if (year < 1000) return `c. AD ${year}`;
    return `c. ${year}`;
}

/** Estimated museum value, scaled by rarity, age and condition (0..1). */
export function estimateValue(entry, conditionFactor = 1) {
    const base = RARITIES[entry.rarity]?.value ?? 100;
    const age = Math.min(ageInYears(entry.year), 12000);
    return Math.round((base * (1 + age / 2500) * conditionFactor) / 10) * 10;
}

export function materialLabel(entry) {
    return MATERIALS[entry.mat]?.label || 'Unknown material';
}
